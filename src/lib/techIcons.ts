function normalize(name: string): string {
  return name
    .trim()
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/\./g, "")
    .replace(/\s+/g, " ")
    .trim();
}

export function techIconSrc(name: string): string | null {
  const key = normalize(name);
  const file = ALIASES[key];
  if (!file) return null;
  return `/tech-icons/${file}.svg`;
}
